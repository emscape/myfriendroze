/**
 * Get USPS zone for a destination zip code (from origin 90210)
 * @param {string} destZip - Destination 5-digit zip code
 * @returns {number} - Zone (1-9)
 */
export function getZone(destZip) {
  if (!destZip || destZip.length < 3) {
    return 5; // Default to middle zone if invalid
  }

  const prefix = destZip.substring(0, 3);

  // Try numeric lookup first
  const numericPrefix = parseInt(prefix, 10);
  if (ZONE_MAP[numericPrefix]) {
    return ZONE_MAP[numericPrefix];
  }

  // Try string lookup (for leading zeros)
  if (ZONE_MAP[prefix]) {
    return ZONE_MAP[prefix];
  }

  // Default zones based on first digit for any missing entries
  const firstDigit = prefix[0];
  const defaultZones = {
    '0': 8, // Northeast
    '1': 8, // Northeast/Mid-Atlantic
    '2': 8, // Mid-Atlantic/Southeast
    '3': 8, // Southeast
    '4': 7, // Midwest/Great Lakes
    '5': 6, // Upper Midwest
    '6': 6, // Midwest
    '7': 6, // South Central
    '8': 4, // Mountain West
    '9': 2, // West Coast
  };

  return defaultZones[firstDigit] || 5;
}

