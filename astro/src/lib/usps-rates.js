/**
 * Get the weight key for the rate table
 * @param {number} weightLbs - Weight in pounds
 * @returns {string|number} - The key to look up in GROUND_ADVANTAGE_RATES
 */
export function getWeightKey(weightLbs) {
  if (weightLbs <= 0) return '4oz';

  // Convert to ounces for sub-pound weights
  const ounces = weightLbs * 16;

  if (ounces <= 4) return '4oz';
  if (ounces <= 8) return '8oz';
  if (ounces <= 12) return '12oz';

  // Round up to nearest pound for 1lb+
  const pounds = Math.ceil(weightLbs);

  // Cap at 70 lbs (USPS maximum)
  return Math.min(pounds, 70);
}

/**
 * Get the shipping rate for a given weight and zone
 * @param {number} weightLbs - Weight in pounds
 * @param {number} zone - USPS zone (1-9)
 * @returns {number} - Shipping rate in dollars
 */
export function getRate(weightLbs, zone) {
  const weightKey = getWeightKey(weightLbs);
  const rates = GROUND_ADVANTAGE_RATES[weightKey];

  if (!rates) {
    throw new Error(`No rates found for weight: ${weightLbs} lbs`);
  }

  // Zone is 1-indexed, array is 0-indexed
  const zoneIndex = Math.max(0, Math.min(8, zone - 1));
  return rates[zoneIndex];
}

/**
 * Get estimated delivery days for a zone
 * @param {number} zone - USPS zone (1-9)
 * @returns {string} - Delivery estimate (e.g., "2-5")
 */
export function getDeliveryDays(zone) {
  return DELIVERY_DAYS[zone] || '2-5';
}
